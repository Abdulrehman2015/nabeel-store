    /**
     * Display the Sales & Product Performance Reports.
     */
    public function index(Request $request): View
    {
        $dates = $this->resolveDateRange($request);
        $startDate = $dates['start'];
        $endDate = $dates['end'];
        $preset = $dates['preset'];

        // Period Summary KPIs
        $kpis = $this->calculatePeriodKpis($startDate, $endDate);

        // All Products with Period Performance Metrics
        $productsPerformance = $this->getProductsPerformance($startDate, $endDate, $request);

        // Top Selling (High Velocity) Products
        $topSelling = $productsPerformance->where('period_qty_sold', '>', 0)
            ->sortByDesc('period_qty_sold')
            ->values()
            ->take(10);

        // Least Selling (Low Movement & Dead Stock) Products
        $leastSelling = $productsPerformance->sortBy('period_qty_sold')
            ->values()
            ->take(10);

        // Category Breakdown in Selected Period
        $categoryBreakdown = $this->getCategoryBreakdown($startDate, $endDate);

        // Daily Trend Data for Chart
        $dailyTrend = $this->getDailyTrend($startDate, $endDate);

        // Channel Breakdown (POS Counter vs Online Web Storefront)
        $channelStats = $this->getChannelStats($startDate, $endDate);

        // Available Categories for filtering table
        $categories = Category::orderBy('name')->get();

        return view('admin.reports.index', compact(
            'startDate',
            'endDate',
            'preset',
            'kpis',
            'topSelling',
            'leastSelling',
            'productsPerformance',
            'categoryBreakdown',
            'dailyTrend',
            'channelStats',
            'categories'
        ));
    }

    /**
     * Export reports to CSV.
     */
    public function export(Request $request): StreamedResponse
    {
        $dates = $this->resolveDateRange($request);
        $startDate = $dates['start'];
        $endDate = $dates['end'];

        $products = $this->getProductsPerformance($startDate, $endDate, $request);

        $filename = 'sales-report-' . $startDate->format('Ymd') . '-to-' . $endDate->format('Ymd') . '.csv';

        return response()->streamDownload(function () use ($products, $startDate, $endDate) {
            $handle = fopen('php://output', 'w');

            // UTF-8 BOM for Excel compatibility
            fprintf($handle, chr(0xEF).chr(0xBB).chr(0xBF));

            // Report Header
            fputcsv($handle, ['N&J MINI MART - SALES & PRODUCT PERFORMANCE REPORT']);
            fputcsv($handle, ['Period:', $startDate->format('d M Y') . ' to ' . $endDate->format('d M Y')]);
            fputcsv($handle, ['Generated At:', now()->format('d M Y, h:i A')]);
            fputcsv($handle, ['Generated By:', auth()->user()->name ?? 'Administrator']);
            fputcsv($handle, []);

            // Column Headers
            fputcsv($handle, [
                'Rank',
                'Product Name',
                'SKU',
                'Category',
                'Retail Price (RM)',
                'Purchase Cost (RM)',
                'Units Sold',
                'Total Revenue (RM)',
                'Total Cost (RM)',
                'Net Profit (RM)',
                'Profit Margin (%)',
                'Current Stock',
                'Tied-up Capital (RM)',
                'Status'
            ]);

            // Data Rows
            $rank = 1;
            foreach ($products as $p) {
                fputcsv($handle, [
                    $rank++,
                    $p->name,
                    $p->sku ?? '-',
                    $p->category->name ?? 'Uncategorized',
                    number_format((float) $p->price, 2, '.', ''),
                    number_format((float) $p->purchase_price, 2, '.', ''),
                    $p->period_qty_sold,
                    number_format((float) $p->period_revenue, 2, '.', ''),
                    number_format((float) $p->computed_period_cost, 2, '.', ''),
                    number_format((float) $p->computed_period_profit, 2, '.', ''),
                    $p->computed_profit_margin . '%',
                    $p->stock_quantity,
                    number_format((float) $p->tied_up_capital, 2, '.', ''),
                    $p->period_qty_sold > 5 ? 'High Seller' : ($p->period_qty_sold > 0 ? 'Moderate' : 'Zero Sales (Dead Stock)')
                ]);
            }

            fclose($handle);
        }, $filename, [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ]);
    }

    /**
     * Resolve start and end dates from preset or custom input.
     */
    private function resolveDateRange(Request $request): array
    {
        $preset = $request->input('preset', 'this_month');

        if ($request->filled('start_date') && $request->filled('end_date')) {
            try {
                $start = Carbon::parse($request->input('start_date'))->startOfDay();
                $end = Carbon::parse($request->input('end_date'))->endOfDay();
                $preset = 'custom';
            } catch (\Exception $e) {
                $start = now()->startOfMonth();
                $end = now()->endOfDay();
                $preset = 'this_month';
            }
        } else {
            switch ($preset) {
                case 'today':
                    $start = now()->startOfDay();
                    $end = now()->endOfDay();
                    break;
                case 'yesterday':
                    $start = now()->subDay()->startOfDay();
                    $end = now()->subDay()->endOfDay();
                    break;
                case '7days':
                    $start = now()->subDays(6)->startOfDay();
                    $end = now()->endOfDay();
                    break;
                case '30days':
                    $start = now()->subDays(29)->startOfDay();
                    $end = now()->endOfDay();
                    break;
                case 'last_month':
                    $start = now()->subMonth()->startOfMonth();
                    $end = now()->subMonth()->endOfMonth();
                    break;
                case 'this_year':
                    $start = now()->startOfYear();
                    $end = now()->endOfDay();
                    break;
                case 'all_time':
                    $firstOrder = Order::oldest('created_at')->first();
                    $start = $firstOrder ? $firstOrder->created_at->startOfDay() : now()->subYear()->startOfDay();
                    $end = now()->endOfDay();
                    break;
                case 'this_month':
                default:
                    $preset = 'this_month';
                    $start = now()->startOfMonth();
                    $end = now()->endOfDay();
                    break;
            }
        }

        return [
            'start' => $start,
            'end' => $end,
            'preset' => $preset,
        ];
    }

    /**
     * Calculate period executive summary KPIs.
     */
    private function calculatePeriodKpis(Carbon $startDate, Carbon $endDate): array
    {
        $ordersQuery = Order::where('order_status', '!=', 'cancelled')
            ->whereBetween('created_at', [$startDate, $endDate]);

        $totalRevenue = (float) $ordersQuery->sum('grand_total');
        $totalOrders = (int) $ordersQuery->count();

        // Calculate Units Sold and COGS
        $soldItems = DB::table('order_items')
            ->join('orders', 'order_items.order_id', '=', 'orders.id')
            ->leftJoin('products', 'order_items.product_id', '=', 'products.id')
            ->where('orders.order_status', '!=', 'cancelled')
            ->whereBetween('orders.created_at', [$startDate, $endDate])
            ->select(
                DB::raw('COALESCE(SUM(order_items.quantity), 0) as total_units_sold'),
                DB::raw('COALESCE(SUM(order_items.line_total), 0) as total_items_revenue'),
                DB::raw('COALESCE(SUM(order_items.quantity * COALESCE(products.purchase_price, products.price * 0.7)), 0) as total_cogs')
            )
            ->first();

        $totalUnitsSold = (int) ($soldItems->total_units_sold ?? 0);
        $totalCogs = (float) ($soldItems->total_cogs ?? 0);

        $grossProfit = $totalRevenue - $totalCogs;
        $profitMargin = $totalRevenue > 0 ? round(($grossProfit / $totalRevenue) * 100, 1) : 0;
        $averageOrderValue = $totalOrders > 0 ? round($totalRevenue / $totalOrders, 2) : 0;

        return [
            'total_revenue' => $totalRevenue,
            'total_orders' => $totalOrders,
            'total_units_sold' => $totalUnitsSold,
            'total_cogs' => $totalCogs,
            'gross_profit' => $grossProfit,
            'profit_margin' => $profitMargin,
            'average_order_value' => $averageOrderValue,
        ];
    }

    /**
     * Query all products merged with period sales metrics.
     */
    private function getProductsPerformance(Carbon $startDate, Carbon $endDate, Request $request)
    {
        // Subquery for sales within the date range
        $periodSalesSubquery = DB::table('order_items')
            ->join('orders', 'order_items.order_id', '=', 'orders.id')
            ->where('orders.order_status', '!=', 'cancelled')
            ->whereBetween('orders.created_at', [$startDate, $endDate])
            ->select(
                'order_items.product_id',
                DB::raw('COALESCE(SUM(order_items.quantity), 0) as qty_sold'),
                DB::raw('COALESCE(SUM(order_items.line_total), 0) as revenue_generated'),
                DB::raw('COUNT(DISTINCT orders.id) as orders_count')
            )
            ->groupBy('order_items.product_id');

        $query = Product::with(['category', 'brand'])
            ->leftJoinSub($periodSalesSubquery, 'sales', function ($join) {
                $join->on('products.id', '=', 'sales.product_id');
            })
            ->select(
                'products.*',
                DB::raw('COALESCE(sales.qty_sold, 0) as period_qty_sold'),
                DB::raw('COALESCE(sales.revenue_generated, 0) as period_revenue'),
                DB::raw('COALESCE(sales.orders_count, 0) as period_orders_count')
            );

        if ($request->filled('category_id') && $request->input('category_id') !== 'all') {
            $query->where('products.category_id', $request->input('category_id'));
        }

        if ($request->filled('search')) {
            $search = '%' . trim($request->input('search')) . '%';
            $query->where(function ($q) use ($search) {
                $q->where('products.name', 'LIKE', $search)
                  ->orWhere('products.sku', 'LIKE', $search);
            });
        }

        $totalPeriodRevenue = (float) DB::table('orders')
            ->where('order_status', '!=', 'cancelled')
            ->whereBetween('created_at', [$startDate, $endDate])
            ->sum('grand_total');

        $products = $query->get()->map(function ($p) use ($totalPeriodRevenue) {
            $qty = (int) $p->period_qty_sold;
            $rev = (float) $p->period_revenue;
            $costPerUnit = (float) ($p->purchase_price ?: ($p->price * 0.70));
            $periodCost = $qty * $costPerUnit;
            $periodProfit = $rev - $periodCost;
            $profitMargin = $rev > 0 ? round(($periodProfit / $rev) * 100, 1) : 0;
            $salesContribution = $totalPeriodRevenue > 0 ? round(($rev / $totalPeriodRevenue) * 100, 1) : 0;
            $tiedUpCapital = (int) $p->stock_quantity * $costPerUnit;

            $p->computed_period_cost = round($periodCost, 2);
            $p->computed_period_profit = round($periodProfit, 2);
            $p->computed_profit_margin = $profitMargin;
            $p->sales_contribution = $salesContribution;
            $p->tied_up_capital = round($tiedUpCapital, 2);

            return $p;
        });

        // Sorting
        $sort = $request->input('sort', 'qty_desc');
        switch ($sort) {
            case 'qty_asc':
                return $products->sortBy('period_qty_sold')->values();
            case 'rev_desc':
                return $products->sortByDesc('period_revenue')->values();
            case 'profit_desc':
                return $products->sortByDesc('computed_period_profit')->values();
            case 'stock_asc':
                return $products->sortBy('stock_quantity')->values();
            case 'tied_up_desc':
                return $products->sortByDesc('tied_up_capital')->values();
            case 'qty_desc':
            default:
                return $products->sortByDesc('period_qty_sold')->values();
        }
    }

    /**
     * Category revenue contribution in period.
     */
    private function getCategoryBreakdown(Carbon $startDate, Carbon $endDate)
    {
        return DB::table('order_items')
            ->join('orders', 'order_items.order_id', '=', 'orders.id')
            ->join('products', 'order_items.product_id', '=', 'products.id')
            ->leftJoin('categories', 'products.category_id', '=', 'categories.id')
            ->where('orders.order_status', '!=', 'cancelled')
            ->whereBetween('orders.created_at', [$startDate, $endDate])
            ->select(
                DB::raw("COALESCE(categories.name, 'Uncategorized') as category_name"),
                DB::raw('SUM(order_items.quantity) as units_sold'),
                DB::raw('SUM(order_items.line_total) as category_revenue')
            )
            ->groupBy('categories.id', 'categories.name')
            ->orderByDesc('category_revenue')
            ->get();
    }

    /**
     * Daily trend points for period chart.
     */
    private function getDailyTrend(Carbon $startDate, Carbon $endDate): array
    {
        $dailyData = DB::table('orders')
            ->where('order_status', '!=', 'cancelled')
            ->whereBetween('created_at', [$startDate, $endDate])
            ->select(
                DB::raw('DATE(created_at) as order_date'),
                DB::raw('SUM(grand_total) as daily_revenue'),
                DB::raw('COUNT(id) as daily_orders')
            )
            ->groupBy(DB::raw('DATE(created_at)'))
            ->orderBy('order_date')
            ->get()
            ->keyBy('order_date');

        $labels = [];
        $revenues = [];
        $ordersCounts = [];

        $diffDays = $startDate->diffInDays($endDate);

        if ($diffDays <= 31) {
            // Daily points
            $current = $startDate->copy();
            while ($current->lte($endDate)) {
                $dStr = $current->format('Y-m-d');
                $labels[] = $current->format('d M');
                $revenues[] = isset($dailyData[$dStr]) ? round((float) $dailyData[$dStr]->daily_revenue, 2) : 0;
                $ordersCounts[] = isset($dailyData[$dStr]) ? (int) $dailyData[$dStr]->daily_orders : 0;
                $current->addDay();
            }
        } else {
            // Group by Month if > 31 days
            $monthlyData = DB::table('orders')
                ->where('order_status', '!=', 'cancelled')
                ->whereBetween('created_at', [$startDate, $endDate])
                ->select(
                    DB::raw("DATE_FORMAT(created_at, '%Y-%m') as order_month"),
                    DB::raw('SUM(grand_total) as monthly_revenue'),
                    DB::raw('COUNT(id) as monthly_orders')
                )
                ->groupBy('order_month')
                ->orderBy('order_month')
                ->get();

            foreach ($monthlyData as $row) {
                $labels[] = Carbon::createFromFormat('Y-m', $row->order_month)->format('M Y');
                $revenues[] = round((float) $row->monthly_revenue, 2);
                $ordersCounts[] = (int) $row->monthly_orders;
            }
        }

        return [
            'labels' => $labels,
            'revenues' => $revenues,
            'orders' => $ordersCounts,
        ];
    }

    /**
     * Sales channel breakdown (In-store POS Counter vs Online Web Storefront).
     */
    private function getChannelStats(Carbon $startDate, Carbon $endDate): array
    {
        $orders = Order::where('order_status', '!=', 'cancelled')
            ->whereBetween('created_at', [$startDate, $endDate])
            ->get();

        $posOrders = $orders->filter(function ($o) {
            return $o->delivery_zone === 'pos_counter' || str_starts_with($o->order_number, 'POS-');
        });

        $onlineOrders = $orders->filter(function ($o) {
            return $o->delivery_zone !== 'pos_counter' && !str_starts_with($o->order_number, 'POS-');
        });

        $posRevenue = (float) $posOrders->sum('grand_total');
        $onlineRevenue = (float) $onlineOrders->sum('grand_total');
        $total = $posRevenue + $onlineRevenue;

        return [
            'pos_revenue' => $posRevenue,
            'pos_orders' => $posOrders->count(),
            'pos_percentage' => $total > 0 ? round(($posRevenue / $total) * 100, 1) : 0,
            'online_revenue' => $onlineRevenue,
            'online_orders' => $onlineOrders->count(),
            'online_percentage' => $total > 0 ? round(($onlineRevenue / $total) * 100, 1) : 0,
        ];
    }
